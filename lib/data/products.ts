export const products: Product[] = seeds.map((s, i) => ({
  id: `p${String(i + 1).padStart(2, '0')}`,
  slug: s.slug,
  name: s.name,
  category: s.category,
  price: s.price,
  compareAtPrice: s.was,
  colors: colors(...s.colors),
  sizes: s.sizes,
  addedAt: s.addedAt,
  rating: s.rating,
  reviews: s.reviews,
  stock: s.stock,
  description: s.description,
  details: s.details,
  image: `/images/products/${s.slug}.jpg`,
}))

